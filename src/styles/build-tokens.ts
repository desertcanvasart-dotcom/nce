/**
 * Pure token builder used by scripts/tokens.ts and its unit tests.
 * Input: the design-system tokens.json and tokens/motion.json, both unedited.
 */

type Themed = { light: string; dark: string };
type Named<V> = { name: string; value: V; usage?: string };
type TypeStyle = {
  name: string;
  fontSize: string;
  lineHeight: number | string;
  fontWeight: number;
  letterSpacing?: string;
  fontStyle?: string;
  usage?: string;
};

export type TokenSource = {
  color: { themes: { id: string; name: string }[]; tokens: Named<string | Themed>[] };
  type: { families: Record<string, string>; groups: { name: string; family: string; styles: TypeStyle[] }[] };
  spacing: { tokens: Named<string>[] };
  radius: { tokens: Named<string>[] };
  shadow: { tokens: Named<string | Themed>[] };
  layout: { tokens: Named<string>[] };
};
export type MotionSource = { motion: { tokens: Named<string>[] } };

/**
 * Self-hosted faces (next/font) are exposed as CSS variables by src/app/fonts.ts.
 * The stacks keep the design system's order; each face falls back to its plain name
 * so a page that does not load a face (e.g. JA faces outside /ja/) still has a valid stack.
 */
export const FONT_FACE_VARS: Record<string, string> = {
  "Cormorant Garamond": "--font-face-cormorant",
  Jost: "--font-face-jost",
  "Noto Serif JP": "--font-face-noto-serif-jp",
  "Noto Sans JP": "--font-face-noto-sans-jp",
};

const isThemed = (v: unknown): v is Themed => typeof v === "object" && v !== null && "light" in v && "dark" in v;

export function fontStack(stack: string): string {
  return stack
    .split(",")
    .map((part) => part.trim())
    .map((part) => {
      const plain = part.replace(/^"|"$/g, "");
      const cssVar = FONT_FACE_VARS[plain];
      return cssVar ? `var(${cssVar}, ${part})` : part;
    })
    .join(", ");
}

/** "Drops to 56px under 720px" in a type style's usage becomes a media rule. */
export function responsiveSize(usage = ""): { size: string; below: string } | null {
  const m = /Drops to (\d+px) under (\d+px)/.exec(usage);
  return m ? { size: m[1]!, below: m[2]! } : null;
}

export function buildTokens(source: TokenSource, motion: MotionSource): { css: string; ts: string } {
  const light: string[] = [];
  const dark: string[] = [];
  const constant: string[] = [];

  for (const t of source.color.tokens) {
    if (isThemed(t.value)) {
      light.push(`  --${t.name}: ${t.value.light};`);
      dark.push(`  --${t.name}: ${t.value.dark};`);
    } else {
      light.push(`  --${t.name}: ${t.value};`);
    }
  }
  for (const t of source.shadow.tokens) {
    if (isThemed(t.value)) {
      light.push(`  --${t.name}: ${t.value.light};`);
      dark.push(`  --${t.name}: ${t.value.dark};`);
    } else {
      constant.push(`  --${t.name}: ${t.value};`);
    }
  }
  for (const group of [source.spacing, source.radius, source.layout, motion.motion]) {
    for (const t of group.tokens) constant.push(`  --${t.name}: ${t.value};`);
  }
  for (const [family, stack] of Object.entries(source.type.families)) {
    constant.push(`  --font-${family}: ${fontStack(stack)};`);
  }

  const classes: string[] = [];
  const media: string[] = [];
  for (const group of source.type.groups) {
    for (const s of group.styles) {
      const p = `--type-${s.name}`;
      constant.push(`  ${p}-size: ${s.fontSize};`);
      constant.push(`  ${p}-line: ${s.lineHeight};`);
      constant.push(`  ${p}-weight: ${s.fontWeight};`);
      constant.push(`  ${p}-tracking: ${s.letterSpacing ?? "normal"};`);
      const decl = [
        `font-family: var(--font-${group.family})`,
        `font-size: var(${p}-size)`,
        `line-height: var(${p}-line)`,
        `font-weight: var(${p}-weight)`,
        `letter-spacing: var(${p}-tracking)`,
      ];
      if (s.fontStyle) decl.push(`font-style: ${s.fontStyle}`);
      classes.push(`.${s.name} { ${decl.join("; ")}; }`);
      const r = responsiveSize(s.usage);
      if (r) media.push(`@media (max-width: ${r.below}) {\n  :root { ${p}-size: ${r.size}; }\n}`);
    }
  }

  const header =
    "/* Generated by scripts/tokens.ts from vendor/design-system/tokens/tokens.json and tokens/motion.json. Do not edit. */";
  const css = [
    header,
    `:root,\n[data-theme="light"] {\n  color-scheme: light;\n${light.join("\n")}\n}`,
    `[data-theme="dark"] {\n  color-scheme: dark;\n${dark.join("\n")}\n}`,
    `:root {\n${constant.join("\n")}\n}`,
    ...media,
    ...classes,
    "",
  ].join("\n");

  const names = (ts: Named<unknown>[]) => ts.map((t) => t.name);
  const tsOut = [
    "// Generated by scripts/tokens.ts. Do not edit.",
    `export const themes = ${JSON.stringify(source.color.themes.map((t) => t.id))} as const;`,
    `export const colorTokens = ${JSON.stringify(names(source.color.tokens))} as const;`,
    `export const spaceTokens = ${JSON.stringify(names(source.spacing.tokens))} as const;`,
    `export const radiusTokens = ${JSON.stringify(names(source.radius.tokens))} as const;`,
    `export const shadowTokens = ${JSON.stringify(names(source.shadow.tokens))} as const;`,
    `export const layoutTokens = ${JSON.stringify(names(source.layout.tokens))} as const;`,
    `export const motionTokens = ${JSON.stringify(names(motion.motion.tokens))} as const;`,
    `export const typeStyles = ${JSON.stringify(source.type.groups.flatMap((g) => g.styles.map((s) => s.name)))} as const;`,
    "export type Theme = (typeof themes)[number];",
    "export type ColorToken = (typeof colorTokens)[number];",
    "export type SpaceToken = (typeof spaceTokens)[number];",
    "export type TypeStyle = (typeof typeStyles)[number];",
    "",
  ].join("\n");

  return { css, ts: tsOut };
}
