/**
 * DATA-014: import the vessel directory as PRIVATE drafts.
 *
 *   pnpm import:vessels <vessels.json>                    dry run: writes docs/imports/vessels-dry-run.md, changes nothing
 *   pnpm import:vessels <vessels.json> --apply --target=local     into the local Docker database
 *   pnpm import:vessels <vessels.json> --apply --target=staging   into staging, only after Faris approves the dry run
 *
 * Production is refused. Existing rows (same source_ref) are never overwritten, so admin edits survive a re-run.
 */
import { createClient } from "@supabase/supabase-js";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import type { Database } from "../src/server/db/database.types";
import { EXCLUDED_FIELDS, planImport, type ImportPlan, type SourceVessel } from "./lib/vessel-import";

const STAGING_REF = "fmidxxcadbuzxaxyohtk"; // public project id of the staging database
const root = resolve(import.meta.dirname, "..");
const args = process.argv.slice(2);
const file = args.find((a) => !a.startsWith("--"));
const apply = args.includes("--apply");
const target = args.find((a) => a.startsWith("--target="))?.split("=")[1];

if (!file) {
  console.error("Usage: pnpm import:vessels <vessels.json> [--apply --target=local|staging]");
  process.exit(2);
}

const records = JSON.parse(readFileSync(resolve(file), "utf8")) as SourceVessel[];
const plan = planImport(records);

// Defence in depth: nothing excluded may appear in what we would write.
const written = JSON.stringify(plan.mapped.map((m) => [m.vessel, m.private]));
for (const r of records) {
  for (const f of ["email", "phone"] as const) {
    const v = r[f];
    if (typeof v === "string" && v.length > 5 && written.includes(v))
      throw new Error(`Excluded field ${f} leaked into the import`);
  }
}

function report(p: ImportPlan): string {
  const withNotes = p.mapped.filter((m) => m.notes.length);
  const filled = (k: "cabin_count" | "max_guests" | "deck_count" | "year_built") =>
    p.mapped.filter((m) => m.vessel[k] != null).length;
  const lines = [
    "# Vessel import: dry run",
    "",
    `Source: \`nile-cruise-marketplace/data/vessels.json\` · generated by \`scripts/import-vessels.ts\` · nothing was written.`,
    "",
    "## Counts",
    "",
    "| | Records |",
    "|---|---|",
    `| Read | ${p.read} |`,
    `| Mapped (would be imported as private drafts) | ${p.mapped.length} |`,
    `| Skipped | ${p.skipped.length} |`,
    `| of which exact duplicates | ${p.duplicates.length} |`,
    `| Sailing dahabiya (\`sail\`) | ${p.byType.sail ?? 0} |`,
    `| Motor cruise ship (\`motor\`) | ${p.byType.motor ?? 0} |`,
    `| Paddle steamer (\`steam\`) | ${p.byType.steam ?? 0} (set by an admin after confirmation) |`,
    `| Records with notes (corrected or partly empty) | ${withNotes.length} |`,
    "",
    "**How complete the facts are** (of the mapped records):",
    "",
    `- cabins ${filled("cabin_count")}, guests ${filled("max_guests")}, decks ${filled("deck_count")}, year built ${filled("year_built")}.`,
    "",
    `**Not imported, by design:** ${EXCLUDED_FIELDS.map((f) => `\`${f}\``).join(", ")}. Contacts, prices and scores are unverified (ADR-013, Q26); facilities and notes wait for the amenity model.`,
    "",
    "## Paddle-steamer candidates (need Faris's confirmation)",
    "",
    "These names suggest a steamer. They are imported as motor ships; an admin changes the type once confirmed.",
    "",
    ...p.steamCandidates.map((c) => `- ${c.name} (\`${c.slug}\`)`),
    "",
    "## Exact duplicates (the first is kept)",
    "",
    ...(p.duplicates.length
      ? p.duplicates.map((d) => `- ${d.name}: kept \`${d.keptSlug}\`, dropped \`${d.droppedSlug}\``)
      : ["None."]),
    "",
    "## Likely duplicates (similar names, all kept, for an admin to merge)",
    "",
    ...(p.likelyDuplicates.length ? p.likelyDuplicates.map((d) => `- ${d.slugs.map((x) => `\`${x}\``).join(" · ")}`) : ["None."]),
    "",
    "## Possible duplicates flagged by the source (both kept, for an admin to merge)",
    "",
    ...(p.flaggedDuplicates.length ? p.flaggedDuplicates.map((d) => `- \`${d.slug}\`: ${d.flag}`) : ["None."]),
    "",
    "## Skipped",
    "",
    ...(p.skipped.length ? p.skipped.map((s) => `- #${s.index} ${s.name}: ${s.reason}`) : ["None."]),
    "",
    "## Corrections and partial records",
    "",
    ...withNotes.map((m) => `- \`${m.vessel.slug}\`: ${m.notes.join("; ")}`),
    "",
  ];
  return lines.join("\n");
}

async function write(p: ImportPlan) {
  let url: string;
  let key: string;
  if (target === "local") {
    const status = JSON.parse(execFileSync("supabase", ["status", "-o", "json"], { encoding: "utf8" })) as Record<string, string>;
    url = status.API_URL!;
    key = status.SERVICE_ROLE_KEY!;
  } else if (target === "staging") {
    url = process.env.NEXT_PUBLIC_SUPABASE_URL ?? "";
    key = process.env.SUPABASE_SECRET_KEY ?? "";
    if (new URL(url).hostname !== `${STAGING_REF}.supabase.co`)
      throw new Error("Refusing: NEXT_PUBLIC_SUPABASE_URL is not the staging project.");
    if (!key) throw new Error("SUPABASE_SECRET_KEY is not set.");
  } else {
    throw new Error("--apply needs --target=local or --target=staging. Production is never a target.");
  }

  const db = createClient<Database>(url, key, { auth: { persistSession: false } });
  let inserted = 0;
  for (let i = 0; i < p.mapped.length; i += 100) {
    const chunk = p.mapped.slice(i, i + 100);
    const { data, error } = await db
      .from("vessels")
      .upsert(
        chunk.map((m) => m.vessel),
        { onConflict: "source_ref", ignoreDuplicates: true },
      )
      .select("id, source_ref");
    if (error) throw error;
    inserted += data.length;
    const ids = new Map(data.map((d) => [d.source_ref, d.id]));
    const priv = chunk
      .filter((m) => ids.has(m.vessel.source_ref))
      .map((m) => ({ vessel_id: ids.get(m.vessel.source_ref)!, ...m.private }));
    if (priv.length) {
      const { error: e2 } = await db.from("vessel_private").upsert(priv, { onConflict: "vessel_id", ignoreDuplicates: true });
      if (e2) throw e2;
    }
  }
  const { count } = await db.from("vessels").select("id", { count: "exact", head: true }).like("source_ref", "ncm:%");
  console.log(`Inserted ${inserted} new private drafts into ${target}; ${count} directory vessels there in total.`);
}

if (apply) {
  write(plan).catch((e: unknown) => {
    console.error(e instanceof Error ? e.message : e);
    process.exit(1);
  });
} else {
  const dir = join(root, "docs/imports");
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "vessels-dry-run.md"), report(plan));
  console.log(
    `Dry run: read ${plan.read}, mapped ${plan.mapped.length} (${Object.entries(plan.byType)
      .map(([k, v]) => `${k} ${v}`)
      .join(", ")}), ` +
      `skipped ${plan.skipped.length} (${plan.duplicates.length} duplicates), steam candidates ${plan.steamCandidates.length}. ` +
      `Report: docs/imports/vessels-dry-run.md`,
  );
}
